import AppKit
import CryptoKit
import Foundation

enum ClipKind: String, Codable, Sendable { case text, image, files }

struct Clip: Codable, Identifiable, Equatable, Sendable {
    var id: UUID
    var createdAt: Date
    var kind: ClipKind
    var preview: String
    var value: String
    var richTextFile: String?
    var digest: String?

    var paths: [String] { kind == .files ? value.split(separator: "\n").map(String.init) : [] }

    func isSameContent(as other: Clip) -> Bool {
        guard kind == other.kind else { return false }
        if kind == .image { return digest != nil && digest == other.digest }
        return value == other.value
    }
}

/// Decides what never enters history.
enum ClipboardPolicy {
    /// Markers from the nspasteboard.org convention, plus older password manager types.
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
        "de.petermaass.pasteboard.concealed", "Pasteboard generator type"
    ]

    static let knownAppNames: [String: String] = [
        "com.apple.Passwords": "Passwords", "com.apple.keychainaccess": "Keychain Access",
        "com.1password.1password": "1Password", "com.agilebits.onepassword7": "1Password 7",
        "com.bitwarden.desktop": "Bitwarden", "org.keepassxc.keepassxc": "KeePassXC"
    ]

    static let defaultExcludedApps = knownAppNames.keys.sorted()

    static func shouldIgnore(types: [String], sourceApp: String?, excludedApps: Set<String>) -> Bool {
        if types.contains(where: ignoredTypes.contains) { return true }
        if let sourceApp, excludedApps.contains(sourceApp) { return true }
        return false
    }
}

@MainActor
final class ClipboardStore: ObservableObject {
    static let enabledKey = "clipboard.enabled"
    static let excludedKey = "clipboard.excludedApps"
    nonisolated static let maximumImageBytes = 10_000_000
    /// Image data larger than this is skipped before any conversion work happens.
    static let maximumSourceImageBytes = 64_000_000

    @Published private(set) var clips: [Clip] = []
    @Published private(set) var isEnabled: Bool
    @Published private(set) var isPaused = false
    @Published private(set) var isAccessDenied = false
    @Published private(set) var excludedApps: [String]

    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private let sourceApp: @MainActor () -> String?
    private let folder: URL
    private let indexURL: URL
    private let retention: TimeInterval = 30 * 24 * 60 * 60
    private let writer = DispatchQueue(label: "com.shaikjaleel.cherrytools.clipboard", qos: .utility)
    private var lastChangeCount: Int
    private var timer: Timer?
    private var imageTasks: [Task<Void, Never>] = []

    init(folder customFolder: URL? = nil, pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard,
         sourceApp: @escaping @MainActor () -> String? = { NSWorkspace.shared.frontmostApplication?.bundleIdentifier }) {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first!
        folder = customFolder ?? support.appendingPathComponent("CherryTools/Clipboard", isDirectory: true)
        indexURL = folder.appendingPathComponent("history.json")
        self.pasteboard = pasteboard
        self.defaults = defaults
        self.sourceApp = sourceApp
        lastChangeCount = pasteboard.changeCount
        isEnabled = defaults.bool(forKey: Self.enabledKey)
        excludedApps = defaults.stringArray(forKey: Self.excludedKey) ?? ClipboardPolicy.defaultExcludedApps
        secureFolder()
        if let data = try? Data(contentsOf: indexURL),
           let saved = try? JSONDecoder().decode([Clip].self, from: data) {
            clips = saved
        }
        prune()
        removeOrphanedFiles()
        updateTimer()
        refreshAccess()
    }

    func setEnabled(_ enabled: Bool) {
        isEnabled = enabled
        defaults.set(enabled, forKey: Self.enabledKey)
        if enabled { isPaused = false }
        skipCurrentContents()
        updateTimer()
    }

    func setPaused(_ paused: Bool) {
        isPaused = paused
        skipCurrentContents()
        updateTimer()
    }

    func exclude(app bundleID: String) {
        guard !excludedApps.contains(bundleID) else { return }
        excludedApps.append(bundleID)
        defaults.set(excludedApps, forKey: Self.excludedKey)
    }

    func include(app bundleID: String) {
        excludedApps.removeAll { $0 == bundleID }
        defaults.set(excludedApps, forKey: Self.excludedKey)
    }

    func refreshAccess() {
        if #available(macOS 15.4, *) {
            isAccessDenied = pasteboard.accessBehavior == .alwaysDeny
        }
    }

    func captureIfChanged() {
        guard isEnabled, !isPaused, pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        refreshAccess()
        guard !isAccessDenied else { return }

        // Reading the type list does not read the contents.
        let types = pasteboard.types ?? []
        guard !ClipboardPolicy.shouldIgnore(types: types.map(\.rawValue), sourceApp: sourceApp(),
                                            excludedApps: Set(excludedApps)) else { return }
        let now = Date()

        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let title = urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) files"
            insert(Clip(id: UUID(), createdAt: now, kind: .files, preview: title,
                        value: urls.map(\.path).joined(separator: "\n")))
        } else if let text = pasteboard.string(forType: .string), !text.isEmpty {
            // Avoid persisting unexpectedly large copied documents.
            let limited = String(text.prefix(200_000))
            let id = UUID()
            var clip = Clip(id: id, createdAt: now, kind: .text,
                            preview: String(limited.replacingOccurrences(of: "\n", with: " ").prefix(120)), value: limited)
            if limited.count == text.count, let rtf = pasteboard.data(forType: .rtf), rtf.count <= 2_000_000 {
                let file = "\(id.uuidString).rtf"
                write(rtf, to: file)
                clip.richTextFile = file
            }
            insert(clip)
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
                  data.count <= Self.maximumSourceImageBytes {
            captureImage(data, at: now)
        }
    }

    private func captureImage(_ data: Data, at date: Date) {
        let task = Task { [weak self] in
            let encoded = await Task.detached(priority: .utility) { Self.encodeImage(data) }.value
            guard let self, let encoded else { return }
            let id = UUID()
            let file = "\(id.uuidString).png"
            let clip = Clip(id: id, createdAt: date, kind: .image, preview: "Image", value: file, digest: encoded.digest)
            if clips.contains(where: { $0.isSameContent(as: clip) }) {
                insert(clip)
            } else {
                write(encoded.png, to: file)
                insert(clip)
            }
        }
        imageTasks.removeAll { $0.isCancelled }
        imageTasks.append(task)
    }

    nonisolated private static func encodeImage(_ data: Data) -> (png: Data, digest: String)? {
        let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
        let isPNG = data.starts(with: [0x89, 0x50, 0x4E, 0x47])
        guard let png = isPNG ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]),
              png.count <= maximumImageBytes else { return nil }
        return (png, digest)
    }

    private func insert(_ clip: Clip) {
        var clip = clip
        if let existing = clips.first(where: { $0.isSameContent(as: clip) }) {
            // Repeated content moves to the top and keeps its saved files.
            if let unused = clip.richTextFile, unused != existing.richTextFile { delete(file: unused) }
            clip.id = existing.id
            clip.value = existing.value
            clip.richTextFile = existing.richTextFile
            clips.removeAll { $0.id == existing.id }
        }
        clips.insert(clip, at: 0)
        prune()
        save()
    }

    @discardableResult
    func restore(_ clip: Clip) -> Bool {
        var restored = false
        switch clip.kind {
        case .text:
            pasteboard.clearContents()
            pasteboard.setString(clip.value, forType: .string)
            if let file = clip.richTextFile, let rtf = try? Data(contentsOf: folder.appendingPathComponent(file)) {
                pasteboard.setData(rtf, forType: .rtf)
            }
            restored = true
        case .files:
            let urls = clip.paths.filter(FileManager.default.fileExists(atPath:)).map { URL(fileURLWithPath: $0) }
            if !urls.isEmpty {
                pasteboard.clearContents()
                restored = pasteboard.writeObjects(urls as [NSURL])
            }
        case .image:
            if let image = NSImage(contentsOf: folder.appendingPathComponent(clip.value)) {
                pasteboard.clearContents()
                restored = pasteboard.writeObjects([image])
            }
        }
        lastChangeCount = pasteboard.changeCount
        return restored
    }

    func imageURL(for clip: Clip) -> URL? {
        clip.kind == .image ? folder.appendingPathComponent(clip.value) : nil
    }

    func filesAreMissing(_ clip: Clip) -> Bool {
        clip.kind == .files && !clip.paths.contains(where: FileManager.default.fileExists(atPath:))
    }

    func remove(_ clip: Clip) {
        clips.removeAll { $0.id == clip.id }
        deleteFiles(of: clip)
        save()
    }

    func clear() {
        clips.forEach(deleteFiles)
        clips.removeAll()
        save()
    }

    /// Waits for queued image and disk work. Used by tests.
    func flush() async {
        for task in imageTasks { await task.value }
        imageTasks.removeAll()
        await withCheckedContinuation { (done: CheckedContinuation<Void, Never>) in
            writer.async { done.resume() }
        }
    }

    private func skipCurrentContents() { lastChangeCount = pasteboard.changeCount }

    private func updateTimer() {
        timer?.invalidate()
        timer = nil
        guard isEnabled, !isPaused else { return }
        let timer = Timer(timeInterval: 1.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.captureIfChanged() }
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func prune() {
        let cutoff = Date().addingTimeInterval(-retention)
        let expired = clips.filter { $0.createdAt < cutoff }
        guard !expired.isEmpty else { return }
        clips.removeAll { $0.createdAt < cutoff }
        expired.forEach(deleteFiles)
        save()
    }

    private func deleteFiles(of clip: Clip) {
        if clip.kind == .image { delete(file: clip.value) }
        if let file = clip.richTextFile { delete(file: file) }
    }

    private func delete(file: String) {
        let url = folder.appendingPathComponent(file)
        writer.async { try? FileManager.default.removeItem(at: url) }
    }

    private func removeOrphanedFiles() {
        var known: Set<String> = [indexURL.lastPathComponent]
        for clip in clips {
            if clip.kind == .image { known.insert(clip.value) }
            if let file = clip.richTextFile { known.insert(file) }
        }
        let files = (try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? []
        for file in files where !known.contains(file) { delete(file: file) }
    }

    private func secureFolder() {
        let manager = FileManager.default
        try? manager.createDirectory(at: folder, withIntermediateDirectories: true)
        try? manager.setAttributes([.posixPermissions: 0o700], ofItemAtPath: folder.path)
        var values = URLResourceValues()
        values.isExcludedFromBackup = true
        var url = folder
        try? url.setResourceValues(values)
        for file in (try? manager.contentsOfDirectory(atPath: folder.path)) ?? [] {
            try? manager.setAttributes([.posixPermissions: 0o600],
                                       ofItemAtPath: folder.appendingPathComponent(file).path)
        }
    }

    private func write(_ data: Data, to file: String) {
        let url = folder.appendingPathComponent(file)
        writer.async { Self.writePrivately(data, to: url) }
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(clips) else { return }
        let url = indexURL
        writer.async { Self.writePrivately(data, to: url) }
    }

    nonisolated private static func writePrivately(_ data: Data, to url: URL) {
        guard (try? data.write(to: url, options: .atomic)) != nil else { return }
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}
